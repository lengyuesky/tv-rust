CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE COLLATE NOCASE,
 verifier TEXT NOT NULL, admin INTEGER NOT NULL DEFAULT 0,
 disabled INTEGER NOT NULL DEFAULT 0, created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS auth_sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 client TEXT NOT NULL, expires_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
INSERT OR IGNORE INTO settings VALUES ('forbid_proxy','false');
CREATE TABLE IF NOT EXISTS subscriptions (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, url TEXT NOT NULL DEFAULT '',
 config TEXT NOT NULL, interval_seconds INTEGER NOT NULL DEFAULT 7200,
 updated_at INTEGER NOT NULL, checked_at INTEGER NOT NULL, error TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS sources (
 id TEXT PRIMARY KEY, subscription_id TEXT NOT NULL REFERENCES subscriptions(id),
 source_key TEXT NOT NULL, name TEXT NOT NULL, api TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '',
 enabled INTEGER NOT NULL DEFAULT 1, present INTEGER NOT NULL DEFAULT 1,
 upstream_enabled INTEGER NOT NULL DEFAULT 1, note TEXT NOT NULL DEFAULT '',
 UNIQUE(subscription_id,source_key)
);
CREATE TABLE IF NOT EXISTS films (
 id TEXT PRIMARY KEY, source_id TEXT NOT NULL REFERENCES sources(id), vod_id TEXT NOT NULL,
 title TEXT NOT NULL, year TEXT NOT NULL DEFAULT '', kind TEXT NOT NULL DEFAULT 'Movie',
 category TEXT NOT NULL DEFAULT '', poster TEXT NOT NULL DEFAULT '', overview TEXT NOT NULL DEFAULT '',
 remarks TEXT NOT NULL DEFAULT '', actor TEXT NOT NULL DEFAULT '', director TEXT NOT NULL DEFAULT '',
 updated_at INTEGER NOT NULL, detailed_at INTEGER NOT NULL DEFAULT 0,
 UNIQUE(source_id,vod_id)
);
CREATE TABLE IF NOT EXISTS episodes (
 id TEXT PRIMARY KEY, film_id TEXT NOT NULL REFERENCES films(id),
 line_name TEXT NOT NULL, line_order INTEGER NOT NULL, title TEXT NOT NULL, number INTEGER NOT NULL,
 url TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, probe TEXT NOT NULL DEFAULT '{}',
 probed_at INTEGER NOT NULL DEFAULT 0, UNIQUE(film_id,line_name,title,number)
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 film_id TEXT NOT NULL REFERENCES films(id), created_at INTEGER NOT NULL,
 PRIMARY KEY(user_id,film_id)
);
CREATE TABLE IF NOT EXISTS progress (
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 film_id TEXT NOT NULL REFERENCES films(id), episode_id TEXT NOT NULL REFERENCES episodes(id),
 position REAL NOT NULL DEFAULT 0, duration REAL NOT NULL DEFAULT 0,
 authority INTEGER NOT NULL DEFAULT 0, updated_at INTEGER NOT NULL,
 PRIMARY KEY(user_id,film_id)
);
CREATE TABLE IF NOT EXISTS plays (
 seq INTEGER PRIMARY KEY AUTOINCREMENT, id TEXT NOT NULL UNIQUE,
 access_hash TEXT NOT NULL UNIQUE, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 auth_hash TEXT NOT NULL, film_id TEXT NOT NULL REFERENCES films(id),
 episode_id TEXT NOT NULL REFERENCES episodes(id), client TEXT NOT NULL,
 mode TEXT NOT NULL DEFAULT 'direct', reason TEXT NOT NULL DEFAULT '',
 state TEXT NOT NULL DEFAULT 'issued', started_at INTEGER NOT NULL, expires_at INTEGER NOT NULL,
 position REAL NOT NULL DEFAULT 0, reports INTEGER NOT NULL DEFAULT 0,
 native_link_hash TEXT NOT NULL DEFAULT '', ended INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS plays_auth_media ON plays(auth_hash,episode_id,seq DESC);
CREATE TABLE IF NOT EXISTS play_events (
 id INTEGER PRIMARY KEY AUTOINCREMENT, play_id TEXT NOT NULL REFERENCES plays(id) ON DELETE CASCADE,
 at INTEGER NOT NULL, mode TEXT NOT NULL, event TEXT NOT NULL, message TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS media_assets (
 id TEXT NOT NULL, play_id TEXT NOT NULL REFERENCES plays(id) ON DELETE CASCADE,
 url TEXT NOT NULL, PRIMARY KEY(play_id,id)
);
CREATE TABLE IF NOT EXISTS preferences (
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 key TEXT NOT NULL, value TEXT NOT NULL, PRIMARY KEY(user_id,key)
);
CREATE TABLE IF NOT EXISTS cache (key TEXT PRIMARY KEY, value TEXT NOT NULL, expires_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS films_source ON films(source_id);
CREATE INDEX IF NOT EXISTS episodes_film ON episodes(film_id,active,line_order,number);
